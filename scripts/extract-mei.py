# Usage: python scripts/extract-mei.py node_modules/@fontsource/noto-serif-jp/files/noto-serif-jp-japanese-400-normal.woff > src/data/mei.ts
# Requires fonttools. Writes the TypeScript module holding SVG outlines of the 不動流 mark (see src/components/Mei.astro).
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

TEXT = "不動流"
GAP = 200  # vertical space between characters, in font units

f = TTFont(sys.argv[1])
upm = f["head"].unitsPerEm
asc = f["hhea"].ascent
gs, cmap = f.getGlyphSet(), f.getBestCmap()
missing = [ch for ch in TEXT if ord(ch) not in cmap]
if missing:
    sys.exit(f"font lacks {''.join(missing)}")

lines = []
for i, ch in enumerate(TEXT):
    pen = SVGPathPen(gs, lambda v: f"{v:.0f}")
    # flip Y and stack vertically: character i starts at y = i * (upm + GAP)
    gs[cmap[ord(ch)]].draw(TransformPen(pen, (1, 0, 0, -1, 0, asc * 0.88 + i * (upm + GAP))))
    lines.append(f"  {{ char: '{ch}', d: '{pen.getCommands()}' }},")

height = len(TEXT) * upm + (len(TEXT) - 1) * GAP
print(f"""/**
 * Outlines of {TEXT} from Noto Serif JP (SIL OFL), {upm} units per em, y pointing down,
 * already stacked vertically. Generated by scripts/extract-mei.py; do not edit by hand.
 * Used by Mei.astro and the Open Graph images.
 */
export const MEI_TEXT = '{TEXT}';
export const MEI_EM = {upm};
export const MEI_GAP = {GAP};
export const MEI_WIDTH = {upm};
export const MEI_HEIGHT = {height + 40};
export const MEI_VIEWBOX = '0 -20 {upm} {height + 40}';
export const meiGlyphs = [
{chr(10).join(lines)}
];""")
